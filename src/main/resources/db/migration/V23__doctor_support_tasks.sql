CREATE TABLE doctor_support_tasks (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    doctor_staff_id BIGINT NOT NULL,
    encounter_id BIGINT NULL,
    title VARCHAR(200) NOT NULL,
    description VARCHAR(2000),
    priority VARCHAR(20) NOT NULL DEFAULT 'NORMAL',
    due_date DATE NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'OPEN',
    outcome VARCHAR(2000),
    revision INT NOT NULL DEFAULT 0,
    created_by BIGINT NOT NULL,
    updated_by BIGINT NOT NULL,
    created_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6),
    updated_at DATETIME(6) NOT NULL DEFAULT CURRENT_TIMESTAMP(6) ON UPDATE CURRENT_TIMESTAMP(6),
    FOREIGN KEY (doctor_staff_id) REFERENCES doctor_profiles(staff_id),
    FOREIGN KEY (encounter_id) REFERENCES encounters(id),
    FOREIGN KEY (created_by) REFERENCES users(id),
    FOREIGN KEY (updated_by) REFERENCES users(id),
    CONSTRAINT chk_support_task_status CHECK (status IN ('OPEN','IN_PROGRESS','DONE','CANCELLED')),
    CONSTRAINT chk_support_task_priority CHECK (priority IN ('NORMAL','HIGH')),
    INDEX ix_support_doctor_status_due (doctor_staff_id,status,due_date),
    INDEX ix_support_status_due (status,due_date),
    INDEX ix_support_encounter (encounter_id)
) ENGINE=InnoDB;
